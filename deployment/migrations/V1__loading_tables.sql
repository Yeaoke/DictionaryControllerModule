CREATE SCHEMA IF NOT EXISTS data;
CREATE SCHEMA IF NOT EXISTS dsa_data_load;

CREATE TABLE IF NOT EXISTS data.direction_type (
    id bigint PRIMARY KEY,
    name varchar(200) NOT NULL,
    is_deleted char(1) NOT NULL DEFAULT 'N' CHECK (is_deleted IN ('Y', 'N')),
    display_order numeric(10, 0),
    search_synonym varchar(100)
);

CREATE TABLE IF NOT EXISTS data.dsa_raw_direction_type (
    id bigint PRIMARY KEY,
    name varchar(100) NOT NULL,
    doc varchar(100),
    sort numeric(10, 0),
    reject_reason varchar(100),
    new_id bigint
);

CREATE TABLE IF NOT EXISTS data.dsa_loaded_version (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_name varchar(100) NOT NULL,
    version varchar(100) NOT NULL
);

-- Fail on existing duplicates; do not silently choose a version or delete data.
ALTER TABLE data.dsa_loaded_version
    ADD CONSTRAINT uk_dsa_loaded_version_entity UNIQUE (entity_name);

CREATE TABLE IF NOT EXISTS data.dsa_load_batch (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_source varchar(10) NOT NULL,
    data_source_url varchar(500) NOT NULL,
    entity_name varchar(100) NOT NULL,
    dsa_table_name varchar(100) NOT NULL,
    data_table_name varchar(100) NOT NULL,
    load_type varchar(20) NOT NULL,
    load_procedure_name varchar(100) NOT NULL,
    current_version varchar(100),
    new_version varchar(100),
    started_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at timestamp with time zone,
    loaded_by varchar(100),
    status varchar(10) NOT NULL,
    rows_current numeric(10, 0),
    rows_current_deleted numeric(10, 0),
    rows_extracted numeric(10, 0),
    rows_rejected numeric(10, 0),
    rows_inserted numeric(10, 0),
    rows_updated numeric(10, 0),
    rows_deleted numeric(10, 0),
    rows_new numeric(10, 0),
    rows_new_deleted numeric(10, 0),
    error_message varchar(1000)
);

ALTER TABLE data.dsa_load_batch
    ALTER COLUMN started_at SET DEFAULT CURRENT_TIMESTAMP;
